// ── DERIVED QUERIES ──

export function getInvestigatorWithProjects(invId) {
  const inv = investigators.find(i => i.id === invId);
  if (!inv) return null;
  const projIds = invProjRelations.filter(r => r.invId === invId).map(r => r.projId);
  const invProjects = projects.filter(p => projIds.includes(p.id));
  return { ...inv, projects: invProjects };
}

export function getProjectDetails(projId) {
  const proj = projects.find(p => p.id === projId);
  if (!proj) return null;
  const invIds = invProjRelations.filter(r => r.projId === projId).map(r => r.invId);
  const pubIds = pubProjRelations.filter(r => r.projId === projId).map(r => r.pubId);
  return {
    ...proj,
    investigators: investigators.filter(i => invIds.includes(i.id)),
    publications:  publications.filter(p => pubIds.includes(p.id)),
  };
}

export function getPublicationWithProject(pubId) {
  const pub = publications.find(p => p.id === pubId);
  if (!pub) return null;
  const rel  = pubProjRelations.find(r => r.pubId === pubId);
  const proj = rel ? projects.find(p => p.id === rel.projId) : null;
  return { ...pub, project: proj || null };
}

export function getAreaDetails(areaName) {
  const areaProjects = projects.filter(p => p.knowledgeArea === areaName);
  const projIds      = areaProjects.map(p => p.id);
  const pubIds       = pubProjRelations.filter(r => projIds.includes(r.projId)).map(r => r.pubId);
  return {
    area: areaName,
    projects: areaProjects,
    publications: publications.filter(p => pubIds.includes(p.id)),
  };
}

export function getColleagues(invId) {
  const inv = investigators.find(i => i.id === invId);
  if (!inv) return null;
  const sharedProjIds = invProjRelations.filter(r => r.invId === invId).map(r => r.projId);
  const colleagueIds  = new Set(
    invProjRelations
      .filter(r => sharedProjIds.includes(r.projId) && r.invId !== invId)
      .map(r => r.invId)
  );
  return {
    ...inv,
    colleagues: investigators.filter(i => colleagueIds.has(i.id)),
  };
}

export function getTopAreas(n = 5) {
  const counts = {};
  projects.forEach(p => { counts[p.knowledgeArea] = (counts[p.knowledgeArea] || 0) + 1; });
  return Object.entries(counts)
    .map(([area, count]) => ({ area, count }))
    .sort((a, b) => b.count - a.count)
    .slice(0, n);
}

export function getTopInstitutions(n = 5) {
  const invProjectCount = {};
  investigators.forEach(inv => {
    const count = invProjRelations.filter(r => r.invId === inv.id).length;
    invProjectCount[inv.institution] = (invProjectCount[inv.institution] || 0) + count;
  });
  return Object.entries(invProjectCount)
    .map(([institution, count]) => ({ institution, count }))
    .sort((a, b) => b.count - a.count)
    .slice(0, n);
}

export function getTopInvestigators(n = 5) {
  return investigators
    .map(inv => ({
      ...inv,
      count: invProjRelations.filter(r => r.invId === inv.id).length,
    }))
    .sort((a, b) => b.count - a.count)
    .slice(0, n);
}

